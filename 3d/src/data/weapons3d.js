// краткий текст оружия: умение типа + свойства
export function weaponText(kind, perks = []) {
  const t = TRAITS[kind], lines = [];
  if (t) lines.push(t.text);
  for (const p of perks) if (PERKS[p]) lines.push(`${PERKS[p].name}: ${PERKS[p].text}`);
  return lines.join(' ');
}
